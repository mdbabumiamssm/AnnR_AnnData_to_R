test_that("modern fixture matches values recorded by Python anndata", {
  skip_if_not_installed("jsonlite")
  e <- expected()$modern
  ad <- read_fixture(fixture("modern.h5ad"))
  expect_s3_class(ad, "AnnR")
  expect_equal(dim(ad), e$shape)
  expect_identical(obs_names(ad), e$obs_names)
  expect_identical(var_names(ad), e$var_names)
  expect_s4_class(ad$X, "dgRMatrix")
  expect_equal(as.matrix(ad$X), e$X_dense, ignore_attr = TRUE)
  expect_s4_class(ad$layers$counts, "dgCMatrix")
  expect_equal(as.matrix(ad$layers$counts), e$counts_dense, ignore_attr = TRUE)
  expect_equal(ad$layers$dense, e$dense, ignore_attr = TRUE)
  expect_s3_class(ad$obs$group, "factor")
  expect_identical(levels(ad$obs$group), e$group_levels)
  expect_identical(as.character(ad$obs$group), e$group)
  expect_true(is.ordered(ad$obs$level))
  expect_identical(levels(ad$obs$level), e$level_levels)
  expect_equal(ad$obs$score, e$score)
  expect_type(ad$obs$count, "integer")
  expect_equal(ad$obs$count, e$count)
  expect_identical(ad$obs$flag, e$flag)
  expect_identical(ad$obs$maybe, as.integer(e$maybe))
  expect_equal(ad$obsm$X_pca, e$X_pca, ignore_attr = TRUE)
  expect_equal(ad$varm$PCs, e$PCs, ignore_attr = TRUE)
  expect_equal(as.matrix(ad$obsp$distances), e$distances_dense, ignore_attr = TRUE)
  expect_equal(dim(ad$raw$X), e$raw_shape)
  expect_equal(sum(ad$raw$X), e$raw_X_sum, tolerance = 1e-6)
  expect_identical(ad$uns$title, "fixture ✓")
  expect_identical(ad$uns$params$metric, "cosine")
  expect_identical(ad$uns$colors, "#000000")
})

test_that("legacy (pre-0.7) layout is read like Python anndata", {
  skip_if_not_installed("jsonlite")
  e <- expected()$legacy
  ad <- suppressWarnings(read_h5ad(fixture("legacy.h5ad")))
  expect_identical(obs_names(ad), e$obs_names)
  expect_s3_class(ad$obs$louvain, "factor")
  expect_identical(as.character(ad$obs$louvain), e$louvain)
  expect_identical(levels(ad$obs$louvain), e$louvain_levels)
  expect_equal(ad$obs$n_genes, e$n_genes)
  expect_equal(ad$var$means, e$means)
  expect_equal(as.matrix(ad$X), e$X_dense, ignore_attr = TRUE)
  expect_equal(dim(ad$raw$X), e$raw_shape)
  expect_identical(sort(names(ad$uns)), e$uns_keys)
})

test_that("selective reading skips slots and keys", {
  ad <- read_fixture(fixture("modern.h5ad"), layers = "counts", obsm = FALSE, raw = FALSE, uns = c("title"))
  expect_identical(names(ad$layers), "counts")
  expect_length(ad$obsm, 0)
  expect_null(ad$raw)
  expect_identical(names(ad$uns), "title")
})

test_that("results do not depend on the number of threads", {
  a <- read_fixture(fixture("modern.h5ad"), threads = 1)
  b <- read_fixture(fixture("modern.h5ad"), threads = 8)
  expect_identical(a, b)
})

test_that("64-bit integers beyond 2^53 survive a round trip exactly", {
  expect_warning(ad <- read_h5ad(fixture("modern.h5ad")), "beyond 2\\^53")
  expect_type(ad$uns$big, "double")
  f <- tmp_h5ad()
  write_h5ad(ad, f)
  back <- read_fixture(f)
  expect_identical(attr(back$uns$big, "h5ad_int64"), attr(ad$uns$big, "h5ad_int64"))
})

test_that("h5ad_info lists the file structure", {
  info <- h5ad_info(fixture("modern.h5ad"))
  expect_true(all(c("X", "X/data", "obs", "layers/counts") %in% info$path))
  expect_identical(info$encoding[info$path == "X"], "csr_matrix")
  expect_identical(info$filters[info$path == "X/data"], "gzip")
})

test_that("single elements can be read on their own", {
  ad <- read_fixture(fixture("modern.h5ad"))
  expect_identical(read_h5ad_elem(fixture("modern.h5ad"), "obsm/X_pca"), ad$obsm$X_pca)
  expect_identical(read_h5ad_elem(fixture("modern.h5ad"), "layers/counts"), ad$layers$counts)
  expect_identical(read_h5ad_elem(fixture("modern.h5ad"), "obs"), ad$obs)
  expect_identical(read_h5ad_elem(fixture("modern.h5ad"), "uns/params"), ad$uns$params)
  expect_error(read_h5ad_elem(fixture("modern.h5ad"), "nope"), "not found")
})
